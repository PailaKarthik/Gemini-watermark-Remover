def merged(lang):
    """Deep-merge a language over English so missing keys fall back."""
    base = T["en"]
    lang_d = T.get(lang) or {}
    if lang == "en" or not lang_d:
        return base

    def dm(a, b):
        out = dict(a)
        for k, v in b.items():
            if isinstance(v, dict) and isinstance(a.get(k), dict):
                out[k] = dm(a[k], v)
            else:
                out[k] = v
        return out

    return dm(base, lang_d)
